// ════════════════════════════════════════════════════════════════════════
//  junoui — build identity
// ════════════════════════════════════════════════════════════════════════
//  Emits dist/js/identity.js: which commit produced THIS build, so "is my
//  change live?" is a question a consumer can ask the app instead of one
//  answered by reading files (20260908-008, narrowed from 20260811-019).
//
//  Run as part of `npm run build`. See docs/identity.md.
// ════════════════════════════════════════════════════════════════════════

import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';

const OUT_DIR = 'dist/js';
const OUT = `${OUT_DIR}/identity.js`;

function git(args) {
  try {
    return execFileSync('git', args, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

function readIdentity() {
  const builtAt = new Date().toISOString();

  // One explicit flag rather than three nulls a reader could mistake for
  // "clean" or "unknown" — a build outside a git checkout (an unpacked
  // tarball, some CI shallow-clone configurations, a container without
  // .git) must say so unmistakably, not emit a plausible-looking absence.
  const isGitTree = git(['rev-parse', '--is-inside-work-tree']) === 'true';
  if (!isGitTree) {
    return { gitAvailable: false, commit: null, branch: null, dirty: null, builtAt };
  }

  const commit = git(['rev-parse', 'HEAD']);
  const branch = git(['rev-parse', '--abbrev-ref', 'HEAD']);
  const status = git(['status', '--porcelain']);

  return {
    gitAvailable: true,
    commit,
    branch,
    dirty: status === null ? null : status.length > 0,
    builtAt,
  };
}

const identity = readIdentity();

const body = `// junoui build identity. Generated by scripts/build-identity.mjs; do not edit.
//
// commit/branch/dirty describe the tree AT BUILD TIME, not now — those are
// different moments, and only the first is knowable from a value baked into
// a generated file. A consumer importing this weeks after the build gets an
// accurate answer to "what tree produced this artefact", never an answer to
// "is the tree dirty right now" — that second question needs a live git
// call in the tree you actually mean, not this constant. builtAt is a BUILD
// timestamp for the same reason: not a publish time, not an install time.
//
// gitAvailable is false when the build ran outside a git checkout (an
// unpacked tarball, some CI shallow-clone configurations, a container with
// no .git) — commit/branch/dirty are then null on purpose, distinguishable
// from "clean" or "unknown" by this flag rather than by null's own shape.
export const IDENTITY = ${JSON.stringify(identity, null, 2)};
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, body);

if (identity.gitAvailable) {
  console.log(
    `✓ identity: ${identity.commit.slice(0, 7)} (${identity.branch}${identity.dirty ? ', dirty' : ''}) → ${OUT}`,
  );
} else {
  console.log(`✓ identity: no git tree found, gitAvailable:false → ${OUT}`);
}
